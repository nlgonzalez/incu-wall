/**
 * Minimal synthetic JPEG byte streams (SOI, optional APP1/Exif, APP0, SOS, EOI). Enough for
 * the marker walker and for Storage uploads in integration tests; not meant to be decoded.
 */
export function jpegBytes({ exif = false }: { exif?: boolean } = {}): Uint8Array {
  const parts: number[] = [0xff, 0xd8];
  if (exif) {
    const payload = [0x45, 0x78, 0x69, 0x66, 0x00, 0x00, 0x4d, 0x4d, 0x00, 0x2a]; // "Exif\0\0MM*"
    parts.push(0xff, 0xe1, 0x00, payload.length + 2, ...payload);
  }
  const jfif = [0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00];
  parts.push(0xff, 0xe0, 0x00, jfif.length + 2, ...jfif);
  parts.push(0xff, 0xda, 0x00, 0x02, 0x11, 0x22, 0x33);
  parts.push(0xff, 0xd9);
  return new Uint8Array(parts);
}
